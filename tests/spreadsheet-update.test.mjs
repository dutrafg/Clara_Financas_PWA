import assert from 'node:assert/strict';
import {blankData} from '../src/legacy/core.mjs';
import {spreadsheetInsights} from '../src/legacy/spreadsheet-insights.mjs';
let count=0;
const equal=(a,b,label)=>{assert.deepEqual(a,b,label);count++};
const fails=(fn,label)=>{assert.throws(fn,Error,label);count++};
const d=blankData();d.accounts[0].openingCents=100000;
d.accounts.push({id:'reserve',name:'Reserva financeira',type:'Reserva',openingCents:350000});
d.budgets.push({category:'Alimentação',limitCents:100000},{category:'Moradia',limitCents:80000});
d.goals.push({id:'g1',name:'Reserva de emergência',targetCents:500000,savedCents:150000,dueDate:'2027-10-01'});
const main=d.accounts[0].id;
const mk=(id,date,kind,status,category,amountCents,paidAt='')=>d.transactions.push({
 id,date,description:id,kind,status,category,amountCents,accountId:main,toAccountId:'',paidAt,note:''});
mk('paid','2026-10-10','Despesa','Realizado','Alimentação',50000,'2026-10-10');
mk('scheduled','2026-11-05','Despesa','Pendente','Moradia',20000);
mk('overdue','2026-10-20','Despesa','Pendente','Alimentação',10000);
mk('far','2027-02-05','Despesa','Pendente','Moradia',25000);
mk('pending_income','2026-11-10','Receita','Pendente','Salário',30000);
const s=spreadsheetInsights(d,'2026-10','2026-10-31');
equal(s.closingCents,400000,'Saldo consolidado no corte');
equal(s.reserveCents,350000,'Saldo de contas de reserva');
equal(s.pendingNext30Cents,30000,'Pendências vencidas e até 30 dias');
equal(s.availableAfter30Cents,370000,'Saldo disponível após compromissos');
equal(s.budgetTotalCents,180000,'Total dos orçamentos');
equal(s.budgetUsedCents,50000,'Orçamentos só usam despesas realizadas');
equal(s.budgetProjectedCents,60000,'Previsto inclui despesa pendente do mês');
equal(s.budgets[0].category,'Alimentação','Top categorias por gastos realizados');
equal(s.goals[0].ratio,.3,'Percentual da meta');
equal(s.goals[0].missingCents,350000,'Valor restante da meta');
equal(s.flow4.length,4,'Quatro meses no painel');
equal(s.flow4[0].month,'2026-10','Mês inicial');
equal(s.flow4[1].month,'2026-11','Projeção inclui novembro');
equal(s.flow4[1].incomingCents,30000,'Receitas futuras agendadas');
equal(s.flow4[1].outgoingCents,20000,'Saídas futuras agendadas');
equal(s.flow4[1].closingCents,410000,'Saldo previsto acumulado');
equal(s.flow4[3].month,'2027-01','Quarto mês consecutivo');
equal(s.flow4[3].closingCents,410000,'Saída posterior não incluída');
equal(d.transactions.length,5,'Leitura não altera lançamentos');
fails(()=>spreadsheetInsights(d,'2026-13','2026-10-31'),'Rejeita mês inválido');
fails(()=>spreadsheetInsights(d,'2026-10','2026-02-30'),'Rejeita data inválida');
console.log('PLANILHA ATUALIZADA: '+count+' verificações de saldos, reservas, orçamento, metas e projeções aprovadas');
