import assert from 'node:assert/strict';
import {blankData,validateBackup} from '../src/legacy/core.mjs';
import {monthlyReport,annualReport,monthlyReportCSV,annualReportCSV} from '../src/legacy/reporting.mjs';
let n=0;const eq=(a,b,m)=>{assert.deepEqual(a,b,m);n++};const bad=(fn,m)=>{assert.throws(fn,Error,m);n++};
const d=blankData(),id=d.accounts[0].id;d.accounts[0].openingCents=10000;
const r0=monthlyReport(d,'2026-10');
eq(r0.summary.income,0,'No income');eq(r0.categories.length,0,'No categories');
eq(r0.summary.consolidatedCents,10000,'Opening account');
const t=(id,date,kind,status,amountCents,description,paidAt='')=>d.transactions.push({id,date,kind,status,amountCents,paidAt,description,category:kind==='Receita'?'Salário':'Alimentação',accountId:d.accounts[0].id,toAccountId:'',note:''});
t('one','2026-10-05','Receita','Realizado',100000,'Salário','2026-10-05');
t('two','2026-10-06','Despesa','Realizado',20000,'Mercado','2026-10-06');
t('three','2026-10-08','Despesa','Pendente',15000,'Almoço');
t('four','2026-11-10','Despesa','Realizado',5000,'Compra','2026-11-10');
t('five','2026-10-04','Despesa','Cancelado',9000,'Cancelada');
t('six','2026-10-07','Despesa','Realizado',1000,'=HYPERLINK("url")','2026-10-07');
const r=monthlyReport(d,'2026-10');
eq(r.summary.income,100000,'Income exact');
eq(r.summary.expense,21000,'Expense exact');
eq(r.summary.net,79000,'Result exact');
eq(r.summary.toPay,15000,'Outstanding exact');
eq(r.summary.count,5,'Report includes canceled and pending');
eq(r.categories[0].cents,21000,'Category aggregated');
eq(r.categories[0].share,1,'Category share exact');
eq(r.transactions.map(t=>t.id),['five','one','two','six','three'],'Stable chronological ordering');
eq(r.accounts[0].balanceCents,84000,'Accounts include November paid movement in current balance');
eq(validateBackup(d),true,'Report did not modify data');
const annual=annualReport(d,'2026');
eq(annual.income,100000,'Annual income');
eq(annual.expense,26000,'Annual expense');
eq(annual.net,74000,'Annual net');
eq(annual.months.length,12,'12 months');
eq(annual.months[9].month,'2026-10','October index');
eq(annual.months[10].expense,5000,'November included');
const csv=monthlyReportCSV(d,'2026-10');
eq(csv.startsWith('\uFEFF'),true,'CSV includes BOM');
eq(csv.includes('\r\n'),true,'Windows compatible CRLF');
eq(csv.includes(';"\'=HYPERLINK'),false,'No raw formula injection in amount');
eq(csv.includes("'=HYPERLINK"),true,'Spreadsheet formula injection neutralized');
eq(csv.includes('"Resultado"'),true,'Financial summary labels');
eq(csv.includes('"Valor (R$)"'),true,'Transaction header');
eq(annualReportCSV(d,'2026').includes('"TOTAL"'),true,'Annual totals exported');
bad(()=>monthlyReport(d,'2026-13'),'Reject invalid month');
bad(()=>annualReport(d,'20xx'),'Reject invalid year');
console.log('ETAPA 9: '+n+' testes de relatórios, agregados, CSV seguro e exportação aprovados');
