import assert from 'node:assert/strict';
import {blankData,validateBackup} from '../src/legacy/core.mjs';
import {dashboardInsights} from '../src/legacy/dashboard.mjs';
import {addDebt} from '../src/legacy/planning.mjs';
let n=0;const eq=(a,b,m)=>{assert.deepEqual(a,b,m);n++};const bad=(fn,m)=>{assert.throws(fn,Error,m);n++};
const d=blankData(),accountId=d.accounts[0].id;d.accounts[0].openingCents=50000;
d.budgets.push({category:'Alimentação',limitCents:10000});
let r=dashboardInsights(d,'2026-10',{today:'2026-10-31'});
eq(r.totalDebtCents,0,'No debts');eq(r.current.totalBalance,50000,'Opening balance');
eq(r.spendingRate,null,'No revenue means no rate');eq(r.exhaustedCount,0,'Budget starts normal');
eq(r.forecast.length,3,'3 month forecast');eq(r.alerts.length,0,'Empty alerts');
const template={kind:'Despesa',description:'Mercado',category:'Alimentação',accountId,toAccountId:'',note:''};
d.transactions.push({...template,id:'one',date:'2026-10-03',paidAt:'2026-10-03',status:'Realizado',amountCents:8000});
d.transactions.push({...template,id:'two',date:'2026-10-03',paidAt:'2026-10-03',status:'Realizado',amountCents:8000});
d.transactions.push({...template,id:'three',date:'2026-10-01',paidAt:'',status:'Pendente',amountCents:3000});
d.transactions.push({id:'income',date:'2026-10-04',paidAt:'2026-10-04',kind:'Receita',status:'Realizado',description:'Salário',category:'Salário',amountCents:40000,accountId,toAccountId:'',note:''});
d.goals.push({id:'goal',name:'Reserva',targetCents:100000,savedCents:25000,dueDate:'2027-06-10'});
const debt=addDebt(d,{name:'Empréstimo',creditor:'Banco teste',totalCents:50000,openingPaidCents:15000,monthlyCents:5000,dueDate:'2027-12-01',category:'Compras'});
r=dashboardInsights(d,'2026-10',{today:'2026-10-31'});
eq(r.current.income,40000,'Income');eq(r.current.expense,16000,'Expense');
eq(r.pendingNetCents,-3000,'Projected pending net');eq(r.totalDebtCents,35000,'Debt balance');
eq(r.goals[0].percentage,.25,'Goal completion');eq(r.goals[0].remainingCents,75000,'Goal remaining');
eq(r.exhaustedCount,1,'Budget exceeded');eq(r.nearLimitCount,0,'Exceeded not counted as near');
eq(r.spendingRate,.4,'Spending ratio');eq(r.netRate,.6,'Net ratio');
eq(r.alerts.some(x=>x.code==='OVERDUE'),true,'Overdue alert');
eq(r.alerts.some(x=>x.code==='BUDGET_OVER'),true,'Over budget alert');
eq(r.auditCount>=2,true,'Audit identifies both overdue and duplicate');
eq(r.accountCount,1,'Active account count');
eq(r.forecast[0].month,'2026-10','Current first month');
eq(r.forecast[2].month,'2026-12','Quarter projection');
eq(r.current.totalBalance,74000,'Realized financial balance');
eq(validateBackup(d),true,'Dashboard does not mutate finance data');
bad(()=>dashboardInsights(d,'2026-13'),'Invalid month rejected');
console.log('ETAPA 8: '+n+' testes de Dashboard Pro, alertas, metas e previsões aprovados');
