import assert from 'node:assert/strict';
import {blankData,validateBackup,migrateData} from '../src/legacy/core.mjs';
import {encryptBackup,decryptBackup,isEncryptedBackup} from '../src/legacy/security.mjs';
import {createLockRecord,verifyLockRecord} from '../src/legacy/lock.mjs';
let n=0;const eq=(a,b,m)=>{assert.deepEqual(a,b,m);n++};const rejects=async(f,m)=>{await assert.rejects(f,Error,m);n++};
const d=blankData();d.accounts[0].openingCents=37500;
d.transactions.push({id:'tx',date:'2026-10-10',paidAt:'2026-10-10',kind:'Receita',category:'Salário',description:'SEGREDO-BANCARIO-EXEMPLO',amountCents:15000,accountId:d.accounts[0].id,toAccountId:'',status:'Realizado',note:''});
const password='Senha local forte e longa 2026';
const encrypted=await encryptBackup(d,password);
eq(isEncryptedBackup(encrypted),true,'Format encrypted');
eq(encrypted.includes('SEGREDO-BANCARIO-EXEMPLO'),false,'Plaintext financial metadata never leaked');
eq(encrypted.includes(d.accounts[0].name),false,'Account name hidden');
const opened=await decryptBackup(encrypted,password);
eq(opened.transactions[0].description,'SEGREDO-BANCARIO-EXEMPLO','Round-trip private fields');
eq(opened.accounts[0].openingCents,37500,'Opening cents intact');
eq(validateBackup(migrateData(opened)),true,'Recovered backup validates');
const again=await encryptBackup(d,password);
eq(encrypted!==again,true,'Unique nonce and salt per backup');
await rejects(()=>decryptBackup(encrypted,'Senha local errada maior 12'),'Wrong password rejected');
await rejects(()=>encryptBackup(d,'123456'),'Short password rejected');
await rejects(()=>decryptBackup('{bad json}',password),'Malformed encrypted backup rejected');
const envelope=JSON.parse(encrypted);
const changed=JSON.stringify({...envelope,version:2});
await rejects(()=>decryptBackup(changed,password),'Unsupported version rejected');
const badSalt=JSON.stringify({...envelope,salt:'AA=='});
await rejects(()=>decryptBackup(badSalt,password),'Invalid nonce/key material rejected');
const payload=envelope.payload;const tampered=JSON.stringify({...envelope,payload:(payload[0]==='A'?'B':'A')+payload.slice(1)});
await rejects(()=>decryptBackup(tampered,password),'Tampered ciphertext fails authentication');
eq(isEncryptedBackup('{"format":"not-clara"}'),false,'Unknown envelope not accepted');
eq(isEncryptedBackup('not-json'),false,'Corrupt envelope not accepted');
const lock=await createLockRecord(password);
eq(lock.includes(password),false,'UI lock never stores plaintext password');
eq(await verifyLockRecord(lock,password),true,'Valid lock passphrase');
eq(await verifyLockRecord(lock,'Senha falsa segura e longa'),false,'Invalid lock passphrase');
eq(await verifyLockRecord('broken',password),false,'Corrupt lock verifier rejected');
const lock2=await createLockRecord(password);
eq(lock!==lock2,true,'Lock salt random');
await rejects(()=>createLockRecord('short'),'Short lock secret rejected');
eq(validateBackup(d),true,'Security workflows do not mutate working database');
console.log('ETAPA 10: '+n+' testes de backup AES-GCM, senha, adulteração e bloqueio aprovados');
