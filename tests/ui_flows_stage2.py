 page.get_by_role('button',name='Configurações',exact=True).first.click()
 page.get_by_label('Tema').select_option('dark')
 check('tema escuro aplicado',page.locator('body').get_attribute('data-theme')=='dark')
 page.get_by_role('checkbox',name='Ocultar valores').check()
 check('privacidade visual',page.get_by_role('checkbox',name='Ocultar valores').is_checked())
