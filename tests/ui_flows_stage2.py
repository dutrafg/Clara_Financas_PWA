 page.get_by_role('button',name='Carregar demonstração').click();page.get_by_role('button',name='Dashboard',exact=True).first.click();page.get_by_text('Dados fictícios importados da planilha.').first.wait_for()
 check('demonstração contém 63 lançamentos',page.locator('body').inner_text().count('Dados fictícios')>=1)
 page.get_by_role('button',name='Configurações',exact=True).first.click()
 page.locator('input[type=file]').set_input_files({'name':'meu-backup.json','mimeType':'application/json','buffer':json.dumps(snap).encode('utf-8')})
 page.get_by_text('Backup restaurado.').wait_for(timeout=3500)
 check('backup JSON restaurado via seletor de arquivos',page.get_by_text('Backup restaurado.').count()==1)
 page.get_by_role('button',name='Começar do zero').click()
