 check('movimentação registrada',page.locator('.toast').inner_text().find('salvo')>=0)
 page.locator('.period-box input').fill('2026-10');page.locator('.period-box input').dispatch_event('change')
 check('despesa contabilizada pelo pagamento', '129,90' in page.locator('.kpi').nth(1).inner_text())
 page.get_by_role('button',name='Movimentações',exact=True).first.click()
 check('tabela e data efetiva presentes',page.locator('tbody').get_by_text('01/10/2026').count()==1)
 page.locator('tbody button[aria-label=Editar]').first.click()
 check('edição preserva vencimento',page.locator('#f-date').input_value()=='2026-09-30')
