import assert from 'node:assert/strict';
import {blankData,validateBackup,migrateData,accountBalance,periodStats} from '../src/legacy/core.mjs';
import {createAccount,updateAccount,archiveAccount,deleteAccount,createCategory,updateCategory,archiveCategory,deleteCategory,setFinancialPreferences,savingsOverview} from '../src/legacy/catalogs.mjs';
let checks=0;
function ok(expression,label){assert.ok(expression,label);checks++;}
function eq(actual,expected,label){assert.deepEqual(actual,expected,label);checks++;}
function bad(callback,label){assert.throws(callback,Error,label);checks++;}
const data=blankData();
const original=data.accounts[0];
const category=data.categories.find(c=>c.name==='Moradia'&&c.group==='Despesa');
ok(original.id,'Conta inicial tem ID');
eq(data.schemaVersion,2,'Backup schema remains v2');
eq(data.settings.monthlySavingsCents,0,'Meta zero por padrão');
eq(data.settings.reviewDay,1,'Dia padrão');
const account=createAccount(data,{name:' Poupança  Brasil ',type:'Conta',openingCents:10000});
eq(account.name,'Poupança Brasil','Whitespace normalized');
eq(account.openingCents,10000,'Opening balance preserved');
eq(accountBalance(data,account.id),10000,'Opening cash balance');
eq(data.accounts.length,2,'Account created');
bad(()=>createAccount(data,{name:'poupança brasil',type:'Conta',openingCents:0}),'Case insensitive duplicate');
bad(()=>createAccount(data,{name:'',type:'Conta',openingCents:0}),'Empty account name');
bad(()=>createAccount(data,{name:'a',type:'Conta',openingCents:0}),'Short account name');
bad(()=>createAccount(data,{name:'A'.repeat(61),type:'Conta',openingCents:0}),'Long account name');
bad(()=>createAccount(data,{name:'Conta Z',type:'Inexistente',openingCents:0}),'Unknown account type');
bad(()=>createAccount(data,{name:'Conta Z',type:'Conta',openingCents:NaN}),'NaN opening');
bad(()=>createAccount(data,{name:'Conta Z',type:'Conta',openingCents:1.5}),'Noninteger opening');
bad(()=>createAccount(data,{name:'Conta Z',type:'Conta',openingCents:1_000_000_000_001}),'Huge opening');
updateAccount(data,account.id,{name:'Reserva de emergência',type:'Carteira',openingCents:-3000});
eq(account.name,'Reserva de emergência','Rename account');
eq(accountBalance(data,account.id),-3000,'Signed opening balance');
eq(account.type,'Carteira','Account type updated');
bad(()=>updateAccount(data,account.id,{name:original.name.toUpperCase(),type:'Conta',openingCents:0}),'Duplicate account rename rejected');
bad(()=>updateAccount(data,'missing',{name:'Conta x',type:'Conta',openingCents:0}),'Unknown account rejected');
const tx={id:'tx1',date:'2026-10-05',paidAt:'2026-10-05',kind:'Despesa',status:'Realizado',description:'Aluguel',category:'Moradia',amountCents:15000,accountId:account.id,toAccountId:'',note:''};
data.transactions.push(tx);
eq(accountBalance(data,account.id),-18000,'Account cash balance after payment');
archiveAccount(data,account.id,true);
eq(account.archived,true,'Archived account flagged');
eq(accountBalance(data,account.id),-18000,'Archived account retains historical balance');
bad(()=>archiveAccount(data,original.id,true),'Cannot archive every account');
archiveAccount(data,account.id,false);
eq(account.archived,false,'Reactivate account');
bad(()=>deleteAccount(data,account.id),'No deletion when transactions refer to account');
const spare=createAccount(data,{name:'Conta temporária',type:'Dinheiro',openingCents:0});
deleteAccount(data,spare.id);
ok(!data.accounts.find(a=>a.id===spare.id),'Unused account deleted');
bad(()=>deleteAccount(data,'none'),'Unknown account delete rejected');
bad(()=>archiveAccount(data,original.id,'true'),'Non-boolean archive rejected');
const extras=createCategory(data,{name:'  Viagens   longas ',group:'Despesa'});
eq(extras.name,'Viagens longas','Category normalized');
bad(()=>createCategory(data,{name:'viagens LONGAS',group:'Despesa'}),'Category name duplicate within type');
const incomeSame=createCategory(data,{name:'Viagens longas',group:'Receita'});
ok(incomeSame.id!==extras.id,'Same name different type allowed');
bad(()=>createCategory(data,{name:'a',group:'Despesa'}),'Category short name rejected');
bad(()=>createCategory(data,{name:'Quebra',group:'Transferência'}),'Invalid category type');
bad(()=>updateCategory(data,'not-found',{name:'Aluguel',group:'Despesa'}),'Unknown category rejected');
data.budgets.push({category:'Moradia',limitCents:45000});
eq(validateBackup(data),true,'Backup valid before category rename');
updateCategory(data,category.id,{name:'Casa e moradia',group:'Despesa'});
eq(data.transactions[0].category,'Casa e moradia','Linked transactions renamed atomically');
eq(data.budgets[0].category,'Casa e moradia','Linked budget renamed atomically');
eq(validateBackup(data),true,'Backup valid after category rename');
eq(periodStats(data,'2026-10').expensesByCategory[0][0],'Casa e moradia','Reports see renamed category');
bad(()=>updateCategory(data,category.id,{name:'Casa e moradia',group:'Receita'}),'Used category cannot switch kind');
bad(()=>updateCategory(data,category.id,{name:'Alimentação',group:'Despesa'}),'Rename into duplicate category rejected');
archiveCategory(data,category.id,true);
eq(category.archived,true,'Category archivable even with financial history');
eq(validateBackup(data),true,'Archived category backup valid');
bad(()=>deleteCategory(data,category.id),'Cannot delete historical category');
archiveCategory(data,category.id,false);
eq(category.archived,false,'Category can reactivate');
updateCategory(data,extras.id,{name:'Viagens internacionais',group:'Receita'});
eq(extras.group,'Receita','Unused category type can change');
deleteCategory(data,extras.id);
ok(!data.categories.find(c=>c.id===extras.id),'Unused category removed');
bad(()=>deleteCategory(data,'unknown'),'Unknown category cannot delete');
bad(()=>archiveCategory(data,incomeSame.id,'false'),'Invalid flag rejected');
setFinancialPreferences(data,{monthlySavingsCents:80000,reviewDay:15});
eq(data.settings.monthlySavingsCents,80000,'Savings target saved in cents');
eq(data.settings.reviewDay,15,'Review day saved');
eq(savingsOverview(data,'2026-10').targetCents,80000,'Savings summary target');
eq(savingsOverview(data,'2026-10').netCents,-15000,'Expenses count as negative result');
eq(savingsOverview(data,'2026-10').achievedCents,0,'Negative result does not count as savings');
eq(savingsOverview(data,'2026-10').remainingCents,80000,'Savings gap calculated');
const earning={...tx,id:'tx2',kind:'Receita',category:'Salário',description:'Salário',amountCents:150000};
data.transactions.push(earning);
const overview=savingsOverview(data,'2026-10');
eq(overview.netCents,135000,'Income less expenses');
eq(overview.remainingCents,0,'Target exceeded');
eq(overview.ratio,135000/80000,'Savings ratio');
eq(overview.reviewDay,15,'Review day carried to dashboard');
bad(()=>setFinancialPreferences(data,{monthlySavingsCents:-1,reviewDay:1}),'Cannot set negative monthly target');
bad(()=>setFinancialPreferences(data,{monthlySavingsCents:1.2,reviewDay:1}),'Fractional cents rejected');
bad(()=>setFinancialPreferences(data,{monthlySavingsCents:0,reviewDay:29}),'Day above 28 rejected');
bad(()=>setFinancialPreferences(data,{monthlySavingsCents:0,reviewDay:0}),'Day zero rejected');
bad(()=>setFinancialPreferences(data,{monthlySavingsCents:0,reviewDay:1.5}),'Noninteger review day rejected');
eq(validateBackup(data),true,'Backup with archived and preferences validates');
const badAcc=structuredClone(data);badAcc.accounts[0].archived='yes';
bad(()=>validateBackup(badAcc),'Backup rejects nonboolean archive flag');
const badCat=structuredClone(data);badCat.categories[0].archived=0;
bad(()=>validateBackup(badCat),'Backup rejects invalid category archive flag');
const badTarget=structuredClone(data);badTarget.settings.monthlySavingsCents=-100;
bad(()=>validateBackup(badTarget),'Backup rejects invalid target');
const badDay=structuredClone(data);badDay.settings.reviewDay=31;
bad(()=>validateBackup(badDay),'Backup rejects invalid review day');
const old=blankData();delete old.settings.monthlySavingsCents;delete old.settings.reviewDay;
eq(validateBackup(old),true,'Legacy schema 2 without new preferences accepted');
const migrated=migrateData(old);
eq(migrated.settings.monthlySavingsCents,0,'Old backups receive safe target default');
eq(migrated.settings.reviewDay,1,'Old backups receive safe review day');
eq(validateBackup(migrated),true,'Migrated old backup validated');
const oldV1={...old,schemaVersion:1};
eq(migrateData(oldV1).schemaVersion,2,'Legacy schema 1 migrates into v2 with preferences');
eq(validateBackup(migrateData(oldV1)),true,'Migrated v1 validates');
console.log('ETAPA 5: '+checks+' testes de contas, categorias, ajustes, histórico e migração aprovados');
